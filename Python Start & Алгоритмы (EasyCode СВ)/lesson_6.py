name = input("Введите ваше имя: ")  
print(f"Добро пожаловать в мир Python, {name}!")  

class_choice = 0  
while class_choice not in [1, 2, 3]:  
    try:  
        class_choice = int(input(" Выберите класс: 1 - Воин; 2 - Маг; 3 - Лучник. Введите номер класса: "))  
    except ValueError:  
        print("Пожалуйста, введите корректное число (1, 2 или 3).")  
  
if class_choice == 1:  
    hero_class = "Воин"  
    health = 100  
    attack = 20  
    defense = 15  
    print(f" Вы выбрали {hero_class}!")  
    print(f"Стартовые ресурсы:Здоровье: {health} Атака: {attack} Защита: {defense}")  
elif class_choice == 2:  
    hero_class = "Маг"  
    health = 80  
    attack = 15  
    mana = 50  
    print(f" Вы выбрали {hero_class}!")  
    print(f"Стартовые ресурсы: Здоровье: {health} Атака: {attack} Мана: {mana}")  
elif class_choice == 3:  
    hero_class = "Лучник"  
    health = 90  
    attack = 18  
    accuracy = 12  
    print(f"\nВы выбрали {hero_class}!")  
    print(f"Стартовые ресурсы: Здоровье: {health} Атака: {attack} Точность: {accuracy}")  
